--Задание 2.
-- Запрос 1. Инструкция select, использующая агрегатные функции в выражениях столбцов
-- сколько раз каждая прививка была сделана детям, первая и последняя дата проведения этой прививки.
select 
	п.название as прививка,
	count(рп.id) as количество_прививок,
	min(рп.дата_прививки) as первая_прививка,
	max(рп.дата_прививки) as последняя_прививка
from прививка п
left join ребенок_прививка рп on п.id = рп.прививка_id
group by п.название;

-- Запрос 2. Инструкция select, использующая предикат exists с вложенным коррелированным подзапросом
-- получить список всех детей, которые получили хотя бы одну прививку
select 
	фио,
	год_рождения,
	адрес,
	телефон_родителей
from ребенок р
where exists (
		select 1
		from ребенок_прививка рп
		where рп.ребенок_id = р.id
	);

-- Запрос 3. Многострочный insert, выполняющий вставку в таблицу результирующего набора данных вложенного подзапроса
-- добавить связь между детьми не имеющим прививок и прививками, которые никому не были назначены
insert into ребенок_прививка (ребенок_id, прививка_id, дата_прививки)
select 
    р.id as ребенок_id,
    п.id as прививка_id,
    current_date as дата_прививки
from ребенок р
cross join прививка п
where not exists (
	select 1 
	from ребенок_прививка рп
	where рп.ребенок_id = р.id
    )
    and not exists (
    	select 1 
    	from ребенок_прививка рп 
    	where рп.прививка_id = п.id
    );

-- Задание 3. Функция, которая находит 5 самых маленьких по объему таблиц. Вывод: таблица, объем в кб.
create or replace function find_smallest_tables()
returns table (table_name text, size_kb bigint) as $$
begin
    return query
    select
        c.relname::text as table_name,
        pg_total_relation_size(c.oid) / 1024 as size_kb -- размер в кб
    from
        pg_class c
    join
        pg_namespace n on c.relnamespace = n.oid
    where
        c.relkind = 'r' -- только таблицы
        and n.nspname not in ('pg_catalog', 'information_schema') -- исключение служебных схем
    order by
        pg_total_relation_size(c.oid) asc
    limit 5;
end;
$$ language plpgsql;

