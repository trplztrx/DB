--Задание 1
-- Создание таблиц
create table if not exists ребенок (
    id serial primary key,
    фио varchar(100) not null,
    год_рождения date not null,
    адрес varchar(255) not null,
    телефон_родителей varchar(20) not null
);

create table if not exists прививка (
    id serial primary key,
    название varchar(100) not null,
    описание text
);

create table if not exists поликлиника (
    id serial primary key,
    название varchar(100) not null,
    год_основания int not null,
    описание text
);

create table if not exists ребенок_прививка (
    id serial primary key,
    ребенок_id int not null,
    прививка_id int not null,
    дата_прививки date not null,
    foreign key (ребенок_id) references ребенок(id) on delete cascade,
    foreign key (прививка_id) references прививка(id) on delete cascade
);

create table if not exists прививка_поликлиника (
    id serial primary key,
    прививка_id int not null,
    поликлиника_id int not null,
    foreign key (прививка_id) references прививка(id) on delete cascade,
    foreign key (поликлиника_id) references поликлиника(id) on delete cascade
);

-- Дроп таблиц
drop table if exists ребенок_прививка cascade;
drop table if exists прививка_поликлиника cascade;
drop table if exists ребенок cascade;
drop table if exists прививка cascade;
drop table if exists поликлиника cascade;

